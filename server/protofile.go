package server

import (
	"cmp"
	"fmt"
	"slices"
	"strconv"
	"strings"
	"unicode"
)

type protoGen struct {
	r     *registry
	taken map[string]bool
	refs  map[string]string
	msgs  []string
}

func (g *protoGen) reserve(name string) string {
	name = protoIdent(name)
	n := name
	for i := 2; g.taken[n]; i++ {
		n = fmt.Sprintf("%s%d", name, i)
	}
	g.taken[n] = true
	return n
}

func (g *protoGen) scalar(k kind) string {
	switch k {
	case kString:
		return "string"
	case kBytes, kJSON:
		return "bytes"
	case kInt32:
		return "int32"
	case kInt64:
		return "int64"
	case kUint32:
		return "uint32"
	case kUint64:
		return "uint64"
	case kFloat:
		return "float"
	case kBool:
		return "bool"
	}
	return "double"
}

func (g *protoGen) typeOf(ps *Schema, hint string) string {
	switch k := g.r.kindOf(ps); k {
	case kArray:
		return g.typeOf(g.r.resolve(ps).Items, hint)
	case kMap:
		return "map<string, " + g.typeOf(g.r.resolve(ps).AdditionalProperties, hint) + ">"
	case kMessage:
		if ps.Ref != "" {
			ref := strings.TrimPrefix(ps.Ref, refPrefix)
			if n, ok := g.refs[ref]; ok {
				return n
			}
			n := g.reserve(ref)
			g.refs[ref] = n
			g.message(n, g.r.resolve(ps))
			return n
		}
		n := g.reserve(hint)
		g.message(n, ps)
		return n
	default:
		return g.scalar(k)
	}
}

func jsonKey(ident string) string {
	return strings.ToLower(strings.ReplaceAll(ident, "_", ""))
}

func uniqueIdent(base string, taken map[string]bool) string {
	ident := base
	for i := 2; taken[jsonKey(ident)]; i++ {
		ident = base + strconv.Itoa(i)
	}
	taken[jsonKey(ident)] = true
	return ident
}

func defaultJSONName(ident string) string {
	var b strings.Builder
	upper := false
	for _, c := range ident {
		if c == '_' {
			upper = true
			continue
		}
		if upper {
			c = unicode.ToUpper(c)
			upper = false
		}
		b.WriteRune(c)
	}
	return b.String()
}

func (g *protoGen) message(name string, s *Schema) {
	slot := len(g.msgs)
	g.msgs = append(g.msgs, "")
	var b strings.Builder
	fmt.Fprintf(&b, "message %s {\n", name)
	required := map[string]bool{}
	for _, n := range s.Required {
		required[n] = true
	}
	idents := map[string]bool{}
	for _, fname := range s.order {
		ps := s.Properties[fname]
		k := g.r.kindOf(ps)
		typ := g.typeOf(ps, name+camel(fname))
		label := ""
		switch {
		case k == kArray:
			label = "repeated "
		case k != kMap && k != kMessage && !required[fname]:
			label = "optional "
		}
		note := ""
		if k == kJSON {
			note = " // JSON text"
		}
		ident := uniqueIdent(protoIdent(fname), idents)
		opt := ""
		if defaultJSONName(ident) != fname {
			opt = fmt.Sprintf(" [json_name = %q]", fname)
		}
		fmt.Fprintf(&b, "  %s%s %s = %d%s;%s\n", label, typ, ident, s.nums[fname], opt, note)
	}
	b.WriteString("}\n")
	g.msgs[slot] = b.String()
}

func (a *API) ProtoFile() string {
	g := &protoGen{r: a.reg, taken: map[string]bool{}, refs: map[string]string{}}
	pkg, svc := "", a.GRPCService
	if i := strings.LastIndex(a.GRPCService, "."); i >= 0 {
		pkg, svc = a.GRPCService[:i], a.GRPCService[i+1:]
	}
	names := make([]string, 0, len(a.grpcMethods))
	for n := range a.grpcMethods {
		names = append(names, n)
	}
	slices.Sort(names)
	var rpcs strings.Builder
	for _, n := range names {
		m := a.grpcMethods[n]
		route := m.op.Method + " " + m.op.Path
		if m.protoErr != nil {
			fmt.Fprintf(&rpcs, "  // %s: %s is only available as application/grpc+json (%v)\n", route, n, m.protoErr)
			continue
		}
		req, resp := g.reserve(n+"Request"), g.reserve(n+"Response")
		g.message(req, m.req)
		g.message(resp, m.resp)
		fmt.Fprintf(&rpcs, "  // %s\n  rpc %s(%s) returns (%s);\n", route, n, req, resp)
	}
	var b strings.Builder
	b.WriteString("// Generated by minato from the registered operations.\n")
	b.WriteString("// Field numbers follow struct field order. Pin them with a `proto:\"N\"` struct tag before publishing.\n")
	b.WriteString("syntax = \"proto3\";\n\n")
	if pkg != "" {
		fmt.Fprintf(&b, "package %s;\n\n", pkg)
	}
	fmt.Fprintf(&b, "service %s {\n%s}\n", cmp.Or(svc, "API"), rpcs.String())
	for _, m := range g.msgs {
		b.WriteString("\n" + m)
	}
	return b.String()
}
